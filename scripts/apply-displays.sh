#!/usr/bin/env bash
# nwg-displays writes its layout to ~/.config/niri/monitor.kdl, but niri
# never reads that file and the live ~/.config/niri/config.kdl is a
# read-only symlink into the Nix store, so nwg-displays changes never
# stick on their own. This copies the `output { ... }` blocks it wrote
# into the tracked niri/config.kdl (between the BEGIN/END markers) and
# applies it with home-manager switch.
set -euo pipefail
cd "$(dirname "$0")/.."

monitor_kdl="$HOME/.config/niri/monitor.kdl"
config_kdl="home-manager/desktop/niri/config.kdl"

if [[ ! -f "$monitor_kdl" ]]; then
    echo "error: $monitor_kdl not found -- arrange your displays with nwg-displays first" >&2
    exit 1
fi

if ! grep -q '^// BEGIN nwg-displays outputs' "$config_kdl"; then
    echo "error: BEGIN/END nwg-displays markers not found in $config_kdl" >&2
    exit 1
fi

outputs="$(grep -v '^// Generated by nwg-displays' "$monitor_kdl")"

awk -v outputs="$outputs" '
    /^\/\/ BEGIN nwg-displays outputs/ { print; print outputs; skip=1; next }
    /^\/\/ END nwg-displays outputs/   { skip=0 }
    skip { next }
    { print }
' "$config_kdl" > "$config_kdl.tmp"
mv "$config_kdl.tmp" "$config_kdl"

echo "Updated $config_kdl from $monitor_kdl:"
git --no-pager diff -- "$config_kdl"

./scripts/switch-home.sh
